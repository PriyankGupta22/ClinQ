import mongoose from "mongoose";

const clinicSchema = new mongoose.Schema(
    {
        clinicName: {
            type: String,
            required: true,
            trim: true
        },

        email: {
            type: String,
            required: true,
            unique: true,
            lowercase: true,
            trim: true
        },

        password: {
            type: String,
            required: true
        },

        role: {
            type: String,
            enum: ["clinicAdmin"],
            default: "clinicAdmin"
        },

        phone: {
            type: String,
            required: true,
            trim: true
        },

        address: {
            street: {
                type: String,
                trim: true
            },

            city: {
                type: String,
                required: true,
                trim: true
            },

            state: {
                type: String,
                required: true,
                trim: true
            },

            pincode: {
                type: String,
                required: true,
                trim: true
            }
        },

        description: {
            type: String,
            trim: true
        },

        isActive: {
            type: Boolean,
            default: true
        }
    },
    {
        timestamps: true
    }
);

const Clinic = mongoose.model("Clinic", clinicSchema);

export default Clinic;